import { afterEach, beforeEach, expect, it, vi } from 'vitest'
function storage() { const entries = new Map<string, string>(); return { get length() { return entries.size }, key: (i: number) => [...entries.keys()][i] ?? null, getItem: (key: string) => entries.get(key) ?? null, setItem: (key: string, value: string) => { entries.set(key, value) }, removeItem: (key: string) => { entries.delete(key) }, clear: () => entries.clear() } }
const session = (id = 'admin', role = 'admin') => localStorage.setItem('auth.sessionSnapshot', JSON.stringify({ user: { id, role } }))
beforeEach(() => { vi.resetModules(); vi.stubGlobal('localStorage', storage()); vi.stubGlobal('sessionStorage', storage()); session() })
afterEach(() => { vi.unstubAllGlobals(); vi.useRealTimers() })

it('reuses a catalog across a full page reload without extending its original expiration', async () => {
  vi.useFakeTimers(); vi.setSystemTime(new Date('2026-11-22T12:00:00Z'))
  const fetch = vi.fn(async () => ['catalog'])
  const first = await import('./queryCache')
  await first.cachedQuery('admin:plans', 60000, fetch)
  vi.resetModules(); vi.advanceTimersByTime(30000)
  const reloaded = await import('./queryCache')
  expect(await reloaded.cachedQuery('admin:plans', 60000, fetch)).toEqual(['catalog'])
  expect(fetch).toHaveBeenCalledTimes(1)
  vi.advanceTimersByTime(30001)
  await reloaded.cachedQuery('admin:plans', 60000, fetch)
  expect(fetch).toHaveBeenCalledTimes(2)
})
it('does not persist credentials, customer lists, invoices or failed catalogs', async () => {
  const cache = await import('./queryCache')
  cache.setCachedQuery('admin:companies', [{ name: 'Private client' }])
  cache.setCachedQuery('company:a:documents', ['invoice'])
  cache.setCachedQuery('company:a:jarvis:credentials-status', { token: 'private' })
  cache.setCachedQuery('admin:plans', { token: 'private' })
  cache.setCachedQuery('company:a:siigo:catalog-bundle', { accountsError: 'Unavailable' })
  expect(sessionStorage.length).toBe(0)
})
it('isolates companies and users and clears persisted values when invalidated', async () => {
  const cache = await import('./queryCache')
  cache.setCachedQuery('company:a:siigo:catalog-bundle', ['a'])
  expect(cache.peekCachedQuery('company:b:siigo:catalog-bundle')).toBeUndefined()
  cache.invalidateQueryCache('company:a:siigo')
  vi.resetModules(); const reloaded = await import('./queryCache')
  expect(reloaded.peekCachedQuery('company:a:siigo:catalog-bundle')).toBeUndefined()
  reloaded.setCachedQuery('admin:plans', ['a'])
  session('other', 'advisor')
  expect(reloaded.peekCachedQuery('admin:plans')).toBeUndefined()
  expect(sessionStorage.length).toBe(0)
})
it('retains a memory fallback if browser storage is blocked or the catalog is too large', async () => {
  sessionStorage.setItem = () => { throw Error('Quota exceeded') }
  const cache = await import('./queryCache')
  expect(await cache.cachedQuery('admin:plans', 60000, async () => ['saved'])).toEqual(['saved'])
  expect(cache.peekCachedQuery('admin:plans')).toEqual(['saved'])
  expect(sessionStorage.length).toBe(0)
})
it('does not repopulate a new user session when an old request finishes', async () => {
  const cache = await import('./queryCache'); let resolve!: (value: string[]) => void
  const request = cache.cachedQuery('admin:plans', 60000, () => new Promise<string[]>(done => { resolve = done }))
  await Promise.resolve(); session('other', 'admin'); resolve(['old-user'])
  await request
  expect(cache.peekCachedQuery('admin:plans')).toBeUndefined(); expect(sessionStorage.length).toBe(0)
})
it('a successful payment invalidates the affected read models immediately', async () => {
  const cache = await import('./queryCache')
  cache.setCachedQuery('admin:companies', ['unpaid']); cache.setCachedQuery('advisor:dashboard:a', ['unpaid'])
  cache.setCachedQuery('admin:plans', ['catalog'])
  const { invalidateBusinessReads } = await import('./businessCacheInvalidation')
  invalidateBusinessReads('post', '/admin/advisor-sales/sale/payment')
  expect(cache.peekCachedQuery('admin:companies')).toBeUndefined(); expect(cache.peekCachedQuery('advisor:dashboard:a')).toBeUndefined()
  expect(cache.peekCachedQuery('admin:plans')).toEqual(['catalog'])
})
it('forced refresh replaces the persisted catalog and logout clears it', async () => {
  const cache = await import('./queryCache')
  await cache.cachedQuery('admin:plans', 60000, async () => ['before'])
  await cache.cachedQuery('admin:plans', 60000, async () => ['after'], { force: true })
  vi.resetModules(); const reloaded = await import('./queryCache')
  expect(reloaded.peekCachedQuery('admin:plans')).toEqual(['after'])
  const { clearTokens } = await import('./authStorage'); clearTokens()
  expect(sessionStorage.length).toBe(0); expect(reloaded.peekCachedQuery('admin:plans')).toBeUndefined()
})
it('keeps oversized catalogs in memory without filling browser storage', async () => {
  const cache = await import('./queryCache'); const large = 'x'.repeat(800000)
  cache.setCachedQuery('admin:cities', large)
  expect(cache.peekCachedQuery('admin:cities')).toBe(large); expect(sessionStorage.length).toBe(0)
})
it('a plan renewal discards cached access and quota so the new period is read immediately', async () => {
  const cache = await import('./queryCache')
  cache.setActiveCompanyId('a')
  cache.setCachedQuery('company:a:subscription-access', [{ canWrite: false }])
  cache.setCachedQuery('company:a:jarvis:subscription-status', { remaining: 0 })
  const { invalidateBusinessReads } = await import('./businessCacheInvalidation')
  invalidateBusinessReads('patch', '/admin/companies/a/integrations/JARVIS/subscription')
  expect(cache.peekCachedQuery('company:a:subscription-access')).toBeUndefined()
  expect(cache.peekCachedQuery('company:a:jarvis:subscription-status')).toBeUndefined()
})
